const build = (rows: Grid): Art => ({ legend: heroColors, rows });

function heroDirection(facing: Facing): HeroDirectionArt {
  const frames = heroFrames[facing];
  const passing = build(frames.walkPassing);
  return {
    stand: build(frames.idle),
    settle: build(frames.idleSettle),
    breathe: build(frames.idleInhale),
    blink: frames.idleBlink ? build(frames.idleBlink) : null,
    inhaleBlink: frames.idleInhaleBlink ? build(frames.idleInhaleBlink) : null,
    walk: [build(frames.walkContactA), passing, build(frames.walkContactB), passing],
    holding: build(heroHolding[facing]),
  };
}

